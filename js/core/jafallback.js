/** 가타카나 낱말 하나를 한글로 옮긴다 */
function kataWord(w) {
  let out = "";
  for (let i = 0; i < w.length; i++) {
    const c = w[i];
    if (c === "ー") {                       // 장음은 우리말에서 적지 아니한다
      continue;
    }
    if (c === "ッ") {                       // 촉음 — 뒤 글자에 받침으로 붙는다
      out += "";
      continue;
    }
    const nxt = w[i + 1];
    if (SMALL[nxt] && KATA[c]) {
      const base = KATA[c];
      const got = YO[base] && YO[base][SMALL[nxt]];
      out += got || base;
      i++;
      continue;
    }
    out += KATA[c] || c;
  }
  // ン 은 앞 글자의 ㄴ 받침으로, 촉음은 ㅅ 받침으로 바꾼다
  out = out.replace(/(.)/g, (m, p) => addJong(p, 19))    // ㅅ
           .replace(/(.)ㄴ/g, (m, p) => addJong(p, 4));         // ㄴ
  return out.replace(/ㄴ/g, "ㄴ").replace(//g, "");
}

/** 한글 음절에 종성을 붙인다 (받침이 이미 있으면 그대로 둔다) */
function addJong(ch, jong) {
  const c = ch.charCodeAt(0);
  if (c < 0xac00 || c > 0xd7a3) return ch;
  if ((c - 0xac00) % 28 !== 0) return ch;
  return String.fromCharCode(c + jong);
}

