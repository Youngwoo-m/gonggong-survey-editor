const toHalf = (s) => s.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xFEE0));

/** 조문 인용 표기(第１７条 등)를 한국어 표기로 */
function normalizeRefs(s) {
  let t = toHalf(s);
  // PDF 에서 자간 강조로 벌어진 한자 사이 공백 제거 (通 則 → 通則)
  for (let i = 0; i < 3; i++) t = t.replace(/([぀-ヿ一-鿿])[ 	]+([぀-ヿ一-鿿])/g, "$1$2");
  t = t.replace(/第\s*(\d+)\s*条の\s*(\d+)/g, "제$1조의$2");
  t = t.replace(/第\s*(\d+)\s*条/g, "제$1조");
  t = t.replace(/第\s*(\d+)\s*編/g, "제$1편");
  t = t.replace(/第\s*(\d+)\s*章/g, "제$1장");
  t = t.replace(/第\s*(\d+)\s*節/g, "제$1절");
  t = t.replace(/第\s*(\d+)\s*款/g, "제$1관");
  t = t.replace(/第\s*(\d+)\s*項/g, "제$1항");
  t = t.replace(/第\s*(\d+)\s*号/g, "제$1호");
  t = t.replace(/別表\s*(\d+)/g, "별표 $1");
  return t;
}

