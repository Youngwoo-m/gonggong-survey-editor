const JOSA = {
  T: ["은", "는"],       // 받침 있음 / 없음
  O: ["을", "를"],
  S: ["이", "가"],
  W: ["과", "와"],
  R: ["으로", "로"],
  I: ["이라", "라"],
};

const CLOSERS = "」』\"'）)]｣";      // 「표고」라 한다 — 닫는 부호는 건너뛴다

/** 앞 글자의 받침을 보고 은/는·을/를·이/가·과/와·으로/로·이라/라 를 고른다 */
function resolveJosa(s) {
  if (s.indexOf(MK) < 0) return s;
  let out = "";
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== MK) { out += s[i]; continue; }
    const pair = JOSA[s[++i]];
    if (!pair) continue;
    const [withJong, noJong] = pair;

    let j = out.length - 1;
    while (j >= 0 && CLOSERS.includes(out[j])) j--;
    const c = j >= 0 ? out.charCodeAt(j) : -1;

    // 한글 음절이 아니면(숫자·한자·라틴) 받침 없는 쪽으로 — 더 자연스럽다
    let noBatchim = true;
    if (c >= 0xAC00 && c <= 0xD7A3) {
      const jong = (c - 0xAC00) % 28;
      noBatchim = jong === 0 || (pair === JOSA.R && jong === 8);   // ㄹ 받침 → '로'
    }
    out += noBatchim ? noJong : withJong;
  }
  return out;
}

/** 실제 치환 — 외부 번역 API 를 쓰려면 이 함수만 교체한다 */
/** PDF 에서 글자 사이에 끼어든 빈칸을 도로 붙인다 — 「ファ イル」「夾 角」 */
function joinJa(s) {
  return String(s || "")
    // 한자 사이에 끼워 넣은 읽기(루비) — 「夾 きょう 角」 은 「夾角」 이다
    .replace(/([一-鿿])[\s　]+[ぁ-ゖ]{2,6}[\s　]+(?=[一-鿿])/g, "$1")
    .replace(/([ァ-ヺー])[\s　]+(?=[ァ-ヺー])/g, "$1")
    .replace(/([一-鿿])[ 	　]+(?=[一-鿿])/g, "$1")
    .replace(/[゜]/g, "°").replace(/[゛]/g, "")
    .replace(/[･]/g, "·");
}



export function translateVia(text, lang) {
  if (!text) return "";
  let out = String(text);
  if (lang !== "en") out = normalizeRefs(joinJa(out));   // 루비를 먼저 걷어 내야 한다
  const rules = lang === "en" ? EN_RULES : JA_RULES;
  for (const r of rules) out = out.replace(r.re, r.v);
  if (lang !== "en") {
    out = polish(out);              // 사전에 없던 조각을 마저 옮긴다 (장음 부호를 살린 채)
    out = out
      .replace(/[（]/g, "(").replace(/[）]/g, ")")
      .replace(/[―ー]/g, "~").replace(/・/g, "·")
      .replace(/、/g, ", ").replace(/。/g, ". ")
      .replace(/\s+/g, " ")
      .replace(/\s+([,.):\]」』])/g, "$1")     // 문장부호 앞의 빈칸 정리
      .replace(/([(\[「『])\s+/g, "$1");
    out = resolveJosa(out).replace(/\s+/g, " ").trim();
  }
  return out;
}

/** 원문 대비 얼마나 번역되었는지 (0~1) — 품질 표시용 */
function coverage(orig, trans, lang) {
  if (!orig) return 1;
  const leftover = lang === "en" ? 0 : (trans.match(/[぀-ヿ一-鿿]/g) || []).length;
  const total = (orig.match(/[぀-ヿ一-鿿]/g) || []).length || 1;
  return Math.max(0, Math.min(1, 1 - leftover / total));
}

/**
 * 트리 전체를 번역해 transTitle / transBody 를 채운다. 원문은 보존.
 * @returns {{nodes:number, coverage:number}}
 */
export function translateTree(tree, lang, { body = true } = {}) {
  let n = 0, sum = 0;
  M.walk(tree, (node) => {
    node.origTitle = node.origTitle || node.title || "";
    node.transTitle = translateVia(node.origTitle, lang);
    sum += coverage(node.origTitle, node.transTitle, lang);
    if (body && node.body) {
      node.origBody = node.origBody || node.body;
      node.transBody = translateVia(node.origBody, lang);
    }
    n += 1;
  });
  return { nodes: n, coverage: n ? sum / n : 0 };
}

/** 사용자가 번역문을 직접 고칠 때 */
export function setTranslation(node, { title, body }) {
  if (title !== undefined) node.transTitle = title;
  if (body !== undefined) node.transBody = body;
  node.transEdited = true;
}

