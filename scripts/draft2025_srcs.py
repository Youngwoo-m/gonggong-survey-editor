# 문장 끝에 붙은 '근거 꼬리' — 「… . 제4장 3, 부록4 F-1」 꼴
TAIL = re.compile(r"\s*(?:[가-힣A-Za-z0-9()「」]+\s+)?"
                  r"(?:제\d+장[^.。]*|부록4\s*[A-Fa-f]-\d+|\[표\s*4-\d+\]|제[\d~·]+조)"
                  r"(?:\s*[,·]\s*(?:제\d+장[^.。]*|부록4\s*[A-Fa-f]-\d+|\[표\s*4-\d+\]|제[\d~·]+조))*\s*$")

CODE = re.compile(r"부록4\s*([A-Fa-f]-\d+)")
SEC = re.compile(r"\[표\s*4-3\]|제4장\s*2\.1\s*원칙\s*[125]|제4장\s*2\.[12]|제4장\s*3|"
                 r"제2\.[234]절|제3\.4절|(?<!편 )제[23]장|제369~372조|제367·381~386조|제373·409조|"
                 r"제441조|제448·449조|제454조|법\s*제92조")


def rewrite(text, fixes):
    """
    text  : 사유 문장
    fixes : {"D-3": "개선 방향 원문", …}
    """
    s = str(text or "")

    # 1) 부록4 코드 → 보고서의 개선 방향 원문
    def _code(m):
        got = fixes.get(m.group(1).upper())
        return got if got else ""
    s = CODE.sub(_code, s)

    # 2) 보고서·원고의 절 표시 → 그 자리의 원문 문장
    def _sec(m):
        key = re.sub(r"\s+", " ", m.group(0)).strip()
        for k, v in SECTION.items():
            if re.sub(r"\s+", " ", k) == key:
                return v
        return ""
    s = SEC.sub(_sec, s)

    # 3) 남은 자리표시 정리
    s = re.sub(r"\s*[,·]\s*(?=[,·]|$)", "", s)
    s = re.sub(r"\s{2,}", " ", s)
    s = re.sub(r"\s+([.,])", r"\1", s)
    s = re.sub(r"(?:^|\s)[,·]\s*", " ", s)
    return s.strip(" ,·")
