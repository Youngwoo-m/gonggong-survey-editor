def main():
    os.makedirs(ANNEX_DIR, exist_ok=True)
    index = {}
    if os.path.exists(INDEX):
        index = json.load(io.open(INDEX, encoding="utf-8"))
    for no, title, items in FORMS:
        xml = form(no, title, items)
        name = "별지%d.xml" % no
        io.open(os.path.join(ANNEX_DIR, name), "w", encoding="utf-8", newline="\n").write(xml)
        tables = [v for k, v in items if k == "table"]
        index["별지%d" % no] = {
            "file": name, "title": title, "tables": len(tables),
            "rows": sum(len(t) for t in tables),
            "cols": max((max(len(r) for r in t) for t in tables), default=0),
        }
        print("  별지 제%d호서식  %s  — 표 %d개 · %d줄"
              % (no, title, len(tables), sum(len(t) for t in tables)))
    json.dump(index, io.open(INDEX, "w", encoding="utf-8", newline="\n"),
              ensure_ascii=False, indent=1)
    print("  %s" % os.path.relpath(INDEX, ROOT))


if __name__ == "__main__":
    main()
