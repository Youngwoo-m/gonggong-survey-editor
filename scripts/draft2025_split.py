# -*- coding: utf-8 -*-
"""
한 조문에 여러 주제가 뒤섞인 조문을 여러 조문으로 나눈다.

두 조문이 유난히 길고(2,400자·3,500자) 주제가 뒤섞여 있다.

  현행 제29조 RTK-GNSS 공공삼각점측량
      작업계획·선점·표지·관측·점검계산·조정계산이 한 조에 들어 있고,
      공정 순서를 정한 항이 맨 뒤에 있으며, 환폐합 점검계산 항이 앞의 항을
      되받는다. 이 장의 다른 조문(작업순서·선점·표지·관측·조정계산)과
      같은 틀로 다섯 조로 나눈다.

  현행 제188조 지하시설물 정위치 편집
      정위치편집·주기·색상·지하시설물 제원·도로시설물 제원 다섯 주제가
      각각 한 항씩이므로 항 경계가 곧 조 경계다. 색상은 RGB 값 나열이어서
      규정 본문보다 도식 기준에 가까우므로 별표로 뺀다.

나누는 자리는 항의 차례가 아니라 항의 첫 문장으로 찾는다 — 앞 단계에서
항이 늘거나 줄어도 엉뚱한 자리에서 갈리지 아니하게 하기 위함이다.
찾지 못하면 소리 없이 넘어가지 아니하고 멈춘다.
"""
import re

import draft2025_defs as DEFS

MARK = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮"

# 색상 별표로 뺄 것 — gendraft2025 가 별표 목록에 올릴 때 쓴다
COLOR_ANNEX = "지하시설물 종류별 표시 색상"


def _hang(paras):
    """항 표시를 다시 매긴다. 한 항뿐이면 표시 없이 문장으로 편다."""
    ps = [DEFS.strip_mark(p).strip() for p in paras if str(p).strip()]
    if len(ps) == 1:
        return ps[0]
    return "\n".join(f"{MARK[i]} {p}" for i, p in enumerate(ps))


def _head(para):
    """항의 첫 줄(각 호를 뺀 머리 문장)"""
    return DEFS.strip_mark(str(para or "")).split("\n")[0].strip()


def _tail(para):
    """항에서 머리 문장을 뺀 나머지(각 호)"""
    body = DEFS.strip_mark(str(para or ""))
    return body.split("\n", 1)[1].strip() if "\n" in body else ""


def _find(paras, *keys):
    """첫 문장에 그 말이 들어 있는 항을 찾는다 — 없으면 멈춘다"""
    for p in paras:
        h = _head(p)
        if all(k in h for k in keys):
            return p
    raise SystemExit(f"[조문 분할] 나눌 자리를 찾지 못했습니다 — {' · '.join(keys)}")


# ───────────────────────── 현행 제29조 RTK-GNSS ─────────────────────────
def _rtk(body):
    ps = DEFS.paras(body)
    plan = _find(ps, "다음 순서로 실시한다")          # 공정 순서
    how = _find(ps, "측위 방식")                      # 관측 방식과 각 호
                                                      # ('간섭 측위'·'간섭측위' 둘 다 걸리게 한다)
    check = _find(ps, "점검계산")                     # 관측 뒤 점검계산
    loop = _find(ps, "환폐합 점검계산")               # 앞 항을 되받던 항
    adj = _find(ps, "조정계산")                       # 조정계산
    site = [p for p in ps if p not in (plan, how, check, loop, adj)]

    # 앞의 항을 되받던 인용을 한 조 안의 인용으로 고친다
    loop_body = re.sub(r"제\s*\d+\s*항제(\d+)호", r"제1항제\1호", DEFS.strip_mark(loop))

    return [
        ("RTK-GNSS 공공삼각점측량의 작업순서",
         _hang([_head(how), DEFS.strip_mark(plan)]),
         "관측 방식과 공정 순서를 맨 앞에 두어 이 장의 다른 측량방식과 틀을 맞춘다",
         "현행 조문에서 맨 뒤에 있던 공정 순서 항을 앞으로 올리고, 관측 방식을 정한 "
         "문장을 그 앞에 둔다"),
        ("RTK-GNSS 공공삼각점측량의 선점 및 표지 설치",
         _hang(site),
         "작업계획·선점·표지 설치를 관측과 갈라 하나의 조로 모은다",
         "현행 조문의 작업계획·선점·미지점 선정·선점도·영구표지 설치에 관한 항을 "
         "이 조로 옮긴다"),
        ("RTK-GNSS 관측",
         _hang(["RTK-GNSS 관측은 다음 각 호에 따라 실시한다.\n" + _tail(how)]),
         "관측의 방법만을 담아 조문 하나로 세운다",
         "현행 조문에서 관측 방식을 정한 항의 각 호를 이 조로 옮긴다. 세트 안의 "
         "관측 횟수를 정한 표도 함께 옮긴다"),
        ("RTK-GNSS 관측의 점검계산",
         _hang([DEFS.strip_mark(check), loop_body]),
         "점검계산과 그 세부인 환폐합 점검계산을 한 조에 모은다",
         "현행 조문에서 서로 떨어져 있던 점검계산 항과 환폐합 점검계산 항을 잇달아 "
         "두고, 뒤의 항이 앞의 항을 가리키던 「제7항제2호」를 같은 조의 "
         "「제1항제2호」로 고친다"),
        ("RTK-GNSS 관측의 조정계산",
         _hang([DEFS.strip_mark(adj)]),
         "조정계산을 이 장의 「공공삼각점측량 조정계산」과 나란히 둔다",
         "현행 조문의 조정계산 항과 그에 딸린 중량·허용범위 표를 이 조로 옮긴다"),
    ]


# ──────────────────── 현행 제188조 지하시설물 정위치 편집 ────────────────────
COLOR_BODY = (
    "① 정위치편집한 도면에 표시하는 시설물의 종류별 기본색상은 별표에서 정한다.\n"
    "② 도로 시설의 표시는 「수치지도작성작업규칙」 또는 「지도도식규칙」을 적용한다.\n"
    "③ 하수도 시설은 시행자의 요구에 따라 같은 색상의 심벌로 오수관로와 우수관로를 "
    "나누어 표시할 수 있다. 이 경우 나누는 방법은 제1항의 별표에서 정한다.")


def _under(body):
    ps = DEFS.paras(body)
    edit = _find(ps, "정위치편집은")
    note = _find(ps, "주기는")
    color = _find(ps, "기본색상")
    spec = _find(ps, "시설물의 제원은")
    road = _find(ps, "도로시설물의 제원")

    # '다른 사항은 제3항의 제원표시방법을 따른다' — 현행의 제3항은 색상이어서
    # 제원 표시 방법이 아니다. 조를 나누면서 같은 조 안의 호를 가리키게 고친다
    spec_body = DEFS.strip_mark(spec).replace(
        "제3항의 제원표시방법을 따른다", "이 조 제6호의 제원 표시 방법을 따른다")

    return [
        ("지하시설물 정위치 편집",
         _hang([DEFS.strip_mark(edit)]),
         "정위치편집의 방법만을 남겨 조문 하나로 세운다",
         "현행 조문에서 주기·색상·제원 표기에 관한 항을 각각 다음 조문으로 옮기고, "
         "이 조에는 정위치편집의 방법에 관한 항만 남긴다"),
        ("주기의 표시",
         _hang([DEFS.strip_mark(note)]),
         "주기의 표시 방법을 따로 세워 찾아 쓰기 쉽게 한다",
         "현행 조문의 주기 표시에 관한 항을 이 조로 옮긴다"),
        ("시설물의 표시 색상",
         COLOR_BODY,
         f"색상은 시설물 종류마다 정한 RGB 값의 나열이어서 규정 본문보다 도식 기준에 "
         f"가까우므로 별표 「{COLOR_ANNEX}」로 옮기고, 이 조는 그 별표를 가리키는 데 "
         f"그친다",
         "현행 조문의 색상 항에 있던 표와 각 호의 색상 값을 별표로 옮긴다. 도로 시설에 "
         "다른 규칙을 적용하는 것과 하수도 시설을 나누어 표시할 수 있다는 것만 이 조에 "
         "남긴다"),
        ("지하시설물 제원의 표기",
         _hang([spec_body]),
         "제원 표기를 지하시설물과 도로시설물로 갈라 각각 조문을 세운다",
         "현행 조문의 시설물 제원 표기에 관한 항을 이 조로 옮기고, 「제3항의 "
         "제원표시방법」이라는 인용을 바로잡는다. 현행의 제3항은 색상을 정한 항이어서 "
         "제원 표시 방법이 아니므로, 같은 조 제6호를 가리키게 한다"),
        ("도로시설물 제원의 표기",
         _hang([DEFS.strip_mark(road)]),
         "도로시설물의 제원 표기를 따로 세운다",
         "현행 조문의 도로시설물 제원 표기에 관한 항을 이 조로 옮긴다"),
    ]


PLAN = {"제29조": _rtk, "제188조": _under}


def parts(legacy_no, body):
    """[(제목, 본문, 개정 사유, 개정 내용)] — 나눌 조문이 아니면 None"""
    fn = PLAN.get(str(legacy_no or ""))
    return fn(body) if fn else None
