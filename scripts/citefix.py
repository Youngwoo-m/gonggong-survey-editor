# -*- coding: utf-8 -*-
r"""checkcites.py 가 짚은 인용 어긋남을 고친다 (작업규정 개정안).

한 자리씩 무엇을 왜 고치는지 아래에 적어 둔다. 뒤에 되돌리려는 사람이
까닭을 알 수 있어야 한다.

  ㉠ 제2조   「시행령」의 약칭 정의가 없음. 다섯 자리에서 쓰는데 정의가
             없으니 무엇의 시행령인지 규정이 밝히지 아니한 셈이다.
             제26호가 「시행규칙」을 정의하는 것과 짝을 맞추어 정의를 둔다.
             호는 **끝에 붙인다** — 가운데 끼우면 뒤의 호 번호가 밀리고,
             이 규정은 이미 제38호(안전관리비)를 그렇게 붙여 두었다.
  ㉡ 제4조   "같은법 시행령" 은 띄어 써야 한다 — "같은 법 시행령".
  ㉢ 제127조 「시설물의 안전관리에 관한 특별법 시행령」은 폐지되고
             「시설물의 안전 및 유지관리에 관한 특별법」으로 바뀌었다.
             이름만 고친다. **별표 1 제5호나목이 새 시행령에서도 같은
             자리인지는 확인하지 못했다** — 사유에 그렇게 적어 둔다.
  ㉣ 제191조 「도로기반시설물정보 통합관리에 관한 지침」은 「도로기반시설물의
             정보 및 시스템 유지관리 지침」으로 바뀌었다(서고 reg62).
  ㉤ 제191조 「지방자치단체의 도로 및 상ㆍ하수도…」의 가운뎃점이 서고와 다름.
             서고(reg64)는 국가법령정보센터에서 받은 것이므로 그 표기를 따른다.
             아래아(ㆍ U+318D)를 가운뎃점(· U+00B7)으로 바꾼다.
  ㉥ 제208조 「…법률」시행령 처럼 낫표를 법률에서 끊었다. ㉠ 에서 「시행령」을
             정의하므로 다른 네 자리와 같이 그냥 '시행령' 으로 적는다.
  ㉦ 제110ㆍ187ㆍ199조 「수치지도작성작업규칙」 → 「수치지도 작성 작업규칙」.
             정식 이름은 띄어 쓴다(서고 reg51, 국토교통부령).

  python scripts\citefix.py            무엇을 고칠지 보여만 준다
  python scripts\citefix.py --write    자료에 적는다
"""
import io
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "data", "draft2025.json")
NL = chr(10)

ARAEA = chr(0x318D)          # ㆍ 아래아
MIDDOT = chr(0xB7)           # · 가운뎃점

# 조 번호 → [(바꾸기 전, 바꾼 뒤, 왜)]
BODY = {
    "4": [("같은법 시행령", "같은 법 시행령",
           "약칭은 띄어 쓴다")],
    "127": [("「시설물의 안전관리에 관한 특별법 시행령」",
             "「시설물의 안전 및 유지관리에 관한 특별법 시행령」",
             "폐지된 법령 이름을 현행 이름으로")],
    "191": [("「도로기반시설물정보 통합관리에 관한 지침」",
             "「도로기반시설물의 정보 및 시스템 유지관리 지침」",
             "바뀐 지침 이름으로"),
            ("도로 및 상" + ARAEA + "하수도의",
             "도로 및 상" + MIDDOT + "하수도의",
             "가운뎃점 표기를 서고와 맞춤")],
    "208": [("「공간정보의 구축 및 관리 등에 관한 법률」시행령",
             "시행령",
             "낫표를 법률에서 끊지 아니하고 약칭을 씀")],
    "110": [("「수치지도작성작업규칙」", "「수치지도 작성 작업규칙」",
             "정식 이름으로")],
    "187": [("「수치지도작성작업규칙」", "「수치지도 작성 작업규칙」",
             "정식 이름으로")],
    "199": [("「수치지도작성작업규칙」", "「수치지도 작성 작업규칙」",
             "정식 이름으로")],
}

# 조 번호 → 「○ 개정 내용」에 붙일 줄 (개조식ㆍ마침표ㆍ가운뎃점 없이)
WHY = {
    "2": ["「시행령」의 약칭 정의를 제39호로 새로 둠.",
          "제5조, 제11조, 제22조, 제90조, 제208조가 「시행령」을 쓰면서도 "
          "무엇의 시행령인지 밝힌 곳이 없었음.",
          "제26호가 「시행규칙」을 정의한 것과 짝을 맞춤."],
    "4": ["「같은법 시행령」을 「같은 법 시행령」으로 띄어 씀."],
    "127": ["「시설물의 안전관리에 관한 특별법 시행령」이 폐지되어 "
            "「시설물의 안전 및 유지관리에 관한 특별법 시행령」으로 고침.",
            "다만 별표 1 제5호나목이 새 시행령에서도 같은 자리인지는 "
            "확인하지 못하였으므로 발령 전에 살펴야 함."],
    "191": ["「도로기반시설물정보 통합관리에 관한 지침」이 "
            "「도로기반시설물의 정보 및 시스템 유지관리 지침」으로 바뀌어 고침.",
            "「지방자치단체의 도로 및 상" + MIDDOT + "하수도의 시설물관리를 위한 "
            "범용프로그램의 기본설계서 및 품질인증기준」의 가운뎃점 표기를 "
            "고시 원문과 맞춤."],
    "208": ["「공간정보의 구축 및 관리 등에 관한 법률」시행령 처럼 낫표를 "
            "법률에서 끊던 것을 제2조제39호의 약칭 「시행령」으로 고침."],
    "110": ["「수치지도작성작업규칙」을 정식 이름인 "
            "「수치지도 작성 작업규칙」으로 고침."],
    "187": ["「수치지도작성작업규칙」을 정식 이름인 "
            "「수치지도 작성 작업규칙」으로 고침."],
    "199": ["「수치지도작성작업규칙」을 정식 이름인 "
            "「수치지도 작성 작업규칙」으로 고침."],
}

NEW_HO = ('39. "시행령"이란 「공간정보의 구축 및 관리 등에 관한 법률 시행령」을 '
          '말한다. <신설>')


def walk(ns):
    for n in ns:
        yield n
        yield from walk(n.get("children") or [])


def add_why(node, lines):
    """「○ 개정 내용」 도막 끝에 줄을 붙인다 — 도막이 없으면 만든다"""
    r = node.get("reason") or "[변경 사유]" + NL
    head = "○ 개정 내용:"
    add = NL.join("* " + t for t in lines)
    if head in r:
        node["reason"] = r.rstrip() + NL + add + NL
    else:
        node["reason"] = r.rstrip() + NL * 2 + head + NL * 2 + add + NL


def main():
    write = "--write" in sys.argv
    d = json.load(io.open(SRC, encoding="utf-8"))
    jo = {}
    for x in walk(d.get("tree") or []):
        if x.get("level") == "조":
            jo[str(x.get("no"))] = x

    done, miss = [], []

    # ㉠ 제2조에 「시행령」 정의를 끝 호로
    j2 = jo.get("2")
    if j2 is None:
        miss.append(("2", "제2조를 찾지 못했습니다"))
    elif '"시행령"이란' in j2["body"]:
        miss.append(("2", "이미 「시행령」 정의가 있습니다 — 건너뜁니다"))
    else:
        if write:
            j2["body"] = j2["body"].rstrip() + NL + NEW_HO
            add_why(j2, WHY["2"])
        done.append(("2", "제39호 「시행령」 정의를 붙임"))

    # ㉡~㉦ 본문 글 바꾸기
    for no in ("4", "110", "127", "187", "191", "199", "208"):
        x = jo.get(no)
        if x is None:
            miss.append((no, "그런 조가 없습니다"))
            continue
        hit = 0
        for old, new, why in BODY[no]:
            n = x["body"].count(old)
            if n == 0:
                miss.append((no, "찾지 못함 — " + old[:34]))
                continue
            if write:
                x["body"] = x["body"].replace(old, new)
            hit += n
            done.append((no, "%s (%d곳) — %s" % (old[:30], n, why)))
        if hit and write:
            add_why(x, WHY[no])

    for no, s in done:
        print("   제%-4s %s" % (no, s))
    if miss:
        print()
        for no, s in miss:
            print("   ! 제%-4s %s" % (no, s))
    print()
    print("고칠 자리 %d · 못 고친 자리 %d" % (len(done), len(miss)))

    if not write:
        print()
        print("시험만 한 것입니다. 적으려면 --write 를 붙이십시오.")
        return
    io.open(SRC, "w", encoding="utf-8", newline=NL).write(
        json.dumps(d, ensure_ascii=False))
    print("자료에 적었습니다 — data/draft2025.json")


if __name__ == "__main__":
    main()
