def walk(ns):
    for n in ns:
        yield n
        yield from walk(n.get("children") or [])


def hangs(body):
    """본문을 항으로 가른다 —— 항 표시를 뗀 글의 목록(호 줄은 그 항에 붙음)"""
    out = []
    for ln in (body or "").split(NL):
        if ln[:1] in CIRC:
            out.append(ln[1:].lstrip())
        elif out:
            out[-1] += NL + ln
        else:
            out.append(ln)
    return out


def join_hangs(hs):
    return NL.join(CIRC[i] + " " + h for i, h in enumerate(hs))


def mok(lines):
    """한 줄씩인 수칙을 목(가.ㆍ나.…)으로"""
    return NL.join("%s. %s" % (GA[i], s) for i, s in enumerate(lines))


def reason(now, ill, basis, why, what):
    b = ["[변경 사유]", "", "○ 현행 규정:", ""] + ["* " + x for x in now]
    b += ["", "○ 현행의 문제:", ""] + ["* " + x for x in ill]
    b += ["", "○ 관련 근거:", ""] + ["* " + x for x in basis]
    b += ["", "○ 개정 사유:", ""] + ["* " + x for x in why]
    b += ["", "○ 개정 내용:", ""] + ["* " + x for x in what]
    return NL.join(b)


