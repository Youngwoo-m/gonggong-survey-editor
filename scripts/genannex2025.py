ESC = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}


def esc(s):
    return "".join(ESC.get(c, c) for c in str(s or ""))


def table(rows):
    """rows: [[cell, …], …] — 첫 줄은 머리줄. 칸은 글 또는 (글, colspan)"""
    wide = max(sum(c[1] if isinstance(c, tuple) else 1 for c in r) for r in rows)
    out = ['  <table rows="%d" cols="%d">' % (len(rows), wide)]
    for ri, row in enumerate(rows):
        out.append("    <row>")
        ci = 0
        for cell in row:
            span = 1
            if isinstance(cell, tuple):
                cell, span = cell
            attr = ' col="%d" row="%d"' % (ci, ri)
            if span > 1:
                attr += ' colspan="%d"' % span
            if ri == 0:
                attr += ' header="1"'
            out.append("      <cell%s>%s</cell>" % (attr, esc(cell)))
            ci += span
        out.append("    </row>")
    out.append("  </table>")
    return "\n".join(out)


def annex(no, title, items):
    body = ['<?xml version="1.0" encoding="UTF-8"?>',
            '<annex id="별표%s" gubun="별표" no="%s" title="%s" '
            'source="작업규정 개정안 초안 (scripts/genannex2025.py)">' % (no, no, esc(title))]
    for kind, v in items:
        body.append("  <text>%s</text>" % esc(v) if kind == "text" else table(v))
    body.append("</annex>")
    return "\n".join(body) + "\n"


