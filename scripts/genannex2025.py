def main():
    os.makedirs(ANNEX_DIR, exist_ok=True)
    index = json.load(io.open(INDEX, encoding="utf-8")) if os.path.exists(INDEX) else {}
    for no, title, items in ANNEXES:
        xml = annex(no, title, items)
        name = "별표%d.xml" % no
        io.open(os.path.join(ANNEX_DIR, name), "w", encoding="utf-8",
                newline="\n").write(xml)
        tables = [v for k, v in items if k == "table"]
        index["별표%d" % no] = {
            "file": name, "title": title, "tables": len(tables),
            "rows": sum(len(t) for t in tables),
            "cols": max((max(sum(c[1] if isinstance(c, tuple) else 1 for c in r)
                             for r in t) for t in tables), default=0),
        }
        print("  별표 %-3d %s  — 표 %d개 · %d줄"
              % (no, title, len(tables), sum(len(t) for t in tables)))
    json.dump(index, io.open(INDEX, "w", encoding="utf-8", newline="\n"),
              ensure_ascii=False, indent=1)
    print("  %s — 모두 %d건" % (os.path.relpath(INDEX, ROOT), len(index)))


if __name__ == "__main__":
    main()
