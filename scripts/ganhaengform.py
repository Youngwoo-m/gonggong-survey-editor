def annex_body(edits, tail):
    """별표의 '서식 변경 내용' — 비교표와 엑셀에 그대로 실린다"""
    lines = ["○ 바뀌는 문구 (편집기에서 붉게 표시됩니다)", ""]
    for e in edits:
        if e.get("to"):
            lines.append("· “%s” → “%s”" % (e["find"], e["to"]))
        elif e.get("add"):
            lines.append("· “%s” 뒤에 “%s” 을 더한다" % (e["find"], e["add"]))
        else:
            lines.append("· “%s” 를 뺀다" % e["find"])
        if e.get("why"):
            lines.append("   — " + e["why"])
    if tail:
        lines += ["", "○ " + tail]
    return NL.join(lines)


