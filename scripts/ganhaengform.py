def walk(nodes):
    for n in nodes or []:
        yield n
        yield from walk(n.get("children"))


def bump(node, kind="수정"):
    """상태를 올린다 — 유지→수정, 이동→이동ㆍ수정. 삭제ㆍ신설은 그대로 둔다"""
    st = node.get("status") or "유지"
    if st in ("삭제", "신설"):
        return st
    if kind == "삭제":
        node["status"] = "삭제"
        return "삭제"
    if st == "유지":
        node["status"] = "수정"
    elif st == "이동":
        node["status"] = "이동·수정"
    return node["status"]


def reason(now, problem, why, plan, effect, worry):
    """다른 마디와 같은 결의 사유 — 현행 / 문제 / 근거 / 개정안 / 효과 / 검토의견"""
    def blk(title, items):
        return ["○ " + title] + ["  · " + x for x in items]
    return NL.join(blk("현행 규정", now) + blk("현행의 문제", problem)
                   + blk("관련 근거", why) + blk("개정안", plan)
                   + blk("기대 효과", effect) + blk("검토의견", worry))


