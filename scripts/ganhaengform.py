    nodes = list(walk(doc.get("tree") or []))
    by_annex = {}
    for n in nodes:
        r = n.get("annexRef")
        if r:
            by_annex[(r.get("gubun"), str(r.get("no")))] = n
    done = []

    # ── 별표 8 삭제 ──
