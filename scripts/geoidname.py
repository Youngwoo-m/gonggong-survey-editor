def swap_lines(text, old, news):
    """줄 하나를 통째로 갈아 끼운다. (새 글, 한 일)"""
    lines = text.split(NL)
    # 새 줄들이 이미 들어가 있으면 건너뛴다 —— 옛 줄을 남겨 두는 바꿈(29ㆍ71)도
    # 있으므로, 옛 줄이 아닌 새 줄을 보아 가린다.
    fresh = [x for x in news if x != old]
    if fresh and all(x in lines for x in fresh):
        return text, "건너뜀"
    hits = [i for i, x in enumerate(lines) if x.strip() == old]
    if len(hits) != 1:
        return text, "못 찾음(%d)" % len(hits)
    i = hits[0]
    return NL.join(lines[:i] + news + lines[i + 1:]), "고침"


def main():
    doc = json.load(io.open(PATH, encoding="utf-8"))
    seen = {}

    def walk(n):
        if isinstance(n, dict):
            if n.get("level") == "조" and n.get("no") in PLAN:
                seen[n["no"]] = n
            for k in ("tree", "children"):
                if k in n:
                    walk(n[k])
        elif isinstance(n, list):
            for v in n:
                walk(v)

    walk(doc["tree"])
    bad = False
    changed = False
    for no, (bodies, reasons, st) in PLAN.items():
        n = seen.get(no)
        if not n:
            print("못 찾음 제%d조" % no)
            bad = True
            continue
        b = n.get("body") or ""
        for old, new in bodies:
            if new in b:
                print("건너뜀 제%d조 본문 …%s…" % (no, new[:26]))
            elif b.count(old) == 1:
                b = b.replace(old, new)
                print("고침   제%d조 본문 …%s…" % (no, new[:26]))
                changed = True
            else:
                print("못 찾음 제%d조 본문 (%d곳) …%s…" % (no, b.count(old), old[:26]))
                bad = True
        n["body"] = b

        r = n.get("reason") or ""
        for old, news in reasons:
            r, how = swap_lines(r, old, news)
            print("%-6s 제%d조 사유 %s…" % (how, no, old[:30]))
            if how == "고침":
                changed = True
            elif how.startswith("못 찾음"):
                bad = True
        n["reason"] = r

        if st:
            was, now = st
            cur = n.get("status")
            if cur == now:
                print("건너뜀 제%d조 상태 (이미 %s)" % (no, now))
            elif cur == was:
                n["status"] = now
                print("고침   제%d조 상태 %s → %s" % (no, was, now))
                changed = True
            else:
                print("못 찾음 제%d조 상태 — 「%s」 를 기대하였으나 「%s」" % (no, was, cur))
                bad = True

    if bad:
        print("\n못 찾은 것이 있어 적지 아니하였음.")
        sys.exit(1)
    if changed:
        io.open(PATH, "w", encoding="utf-8").write(json.dumps(doc, ensure_ascii=False))
        print("\n%s 을 다시 적었음." % PATH)
    else:
        print("\n고칠 것이 없었음.")


if __name__ == "__main__":
    main()
