def strip_from(body):
    """본문에서 약칭 괄호를 지운다. (바뀐 본문, 지운 약칭 목록)"""
    out, got = body or "", []
    for term, (_, paren, _no) in ALIAS.items():
        if paren and paren in out:
            out = out.replace(paren, "")
            got.append(term)
    # 괄호를 지우면서 생긴 겹공백을 다듬는다
