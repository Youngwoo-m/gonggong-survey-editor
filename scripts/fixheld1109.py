def walk(ns):
    for n in ns:
        yield n
        yield from walk(n.get("children") or [])


def first_item(body, head):
    """정의 조의 호 가운데 head 로 시작하는 것을 제1호로 올리고 번호를 다시 매긴다"""
    lines = body.split(NL)
    items = [i for i, ln in enumerate(lines) if re.match(r"\d+\. ", ln)]
    k = next(i for i in items if lines[i].split(". ", 1)[1].startswith(head))
    if k == items[0]:
        return body
    moved = [lines[k]] + [lines[i] for i in items if i != k]
    for j, i in enumerate(items):
        lines[i] = "%d. %s" % (j + 1, moved[j].split(". ", 1)[1])
    return NL.join(lines)


def bump(n, reg):
    """본문을 고친 조의 상태와 현행 본문을 맞춘다"""
    st = n.get("status") or "유지"
    to = {"유지": "수정", "이동": "이동·수정"}.get(st, st)
    if to != st:
        n["status"] = to
    key = str(n.get("legacyNo") or "").replace(" ", "")
    if key and not n.get("wasBody") and key in reg:
        n["wasBody"] = reg[key]


