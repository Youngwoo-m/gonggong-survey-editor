def apply(no, body):
    """조문 본문에 검토의견을 반영한다. (바뀐 본문, 반영 건수)"""
    rules = AMEND.get(no)
    if not rules:
        return body, 0
    out, n = body or "", 0
    for rule in rules:
        if rule[0] == "sub":
            _, old, new = rule
            if old in out:
                out = out.replace(old, new, 1)
                n += 1
        elif rule[0] == "add":
            out = (out.rstrip() + "\n" + rule[1].strip()).strip()
            n += 1
        elif rule[0] == "cut":
            # 그 말머리로 시작하는 호(號) 한 줄을 통째로 지운다
            head = rule[1]
            lines, keep, hit = out.split("\n"), [], False
            for ln in lines:
                if ln.lstrip().startswith(head):
                    hit = True
                    continue
                keep.append(ln)
            if hit:
                out = "\n".join(keep)
                n += 1
    return out, n
