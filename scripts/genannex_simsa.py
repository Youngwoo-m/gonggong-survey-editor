ESC = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}


def esc(s):
    return "".join(ESC.get(c, c) for c in str(s or ""))


def table(rows):
    """rows: [[cell, …], …]  — 첫 줄은 머리줄로 본다. 셀은 글 또는 (글, colspan)"""
    out = [f'  <table rows="{len(rows)}" cols="{max(len(r) for r in rows)}">']
    for ri, row in enumerate(rows):
        out.append("    <row>")
        ci = 0
        for cell in row:
            span = 1
            if isinstance(cell, tuple):
                cell, span = cell
            attr = f' col="{ci}" row="{ri}"'
            if span > 1:
                attr += f' colspan="{span}"'
            if ri == 0:
                attr += ' header="1"'
            out.append(f"      <cell{attr}>{esc(cell)}</cell>")
            ci += span
        out.append("    </row>")
    out.append("  </table>")
    return "\n".join(out)


def annex(no, title, items):
    """items: ('text', 글) 또는 ('table', rows)"""
    body = [f'<?xml version="1.0" encoding="UTF-8"?>',
            f'<annex id="별표{no}" gubun="별표" no="{no}" title="{esc(title)}" '
            f'source="성과심사 규정 개정안 초안 (scripts/genannex_simsa.py)">']
    for kind, v in items:
        if kind == "text":
            body.append(f"  <text>{esc(v)}</text>")
        else:
            body.append(table(v))
    body.append("</annex>")
    return "\n".join(body) + "\n"


