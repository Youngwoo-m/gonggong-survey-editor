def add(node, benefits, objections):
    """사유 끝에 [이익]ㆍ[예상 반론] 줄을 붙인다 —— 이미 있으면 붙이지 아니한다"""
    r = node.get("reason") or ""
    if "[이익]" in r or "[예상 반론]" in r:
        return False
    lines = ["○ 기대 효과와 예상 반론 (2026-09-07 더함):", ""]
    lines += ["* [이익] " + x for x in benefits]
    lines += ["* [예상 반론] " + x for x in objections]
    node["reason"] = (r.rstrip() + NL + NL + NL.join(lines)) if r else NL.join(lines)
    return True


def main():
    doc = json.load(io.open(SRC, encoding="utf-8"))
    by = {}
    for n in walk(doc.get("tree") or []):
        if n.get("level") == "조" and not n.get("annexRef") and n.get("no"):
            by.setdefault(n["no"], n)

    done, skip, miss = 0, 0, []
    for no, (ben, obj) in sorted(JOBS.items()):
        n = by.get(no)
        if n is None:
            miss.append(no)
            continue
        if add(n, ben, obj):
            done += 1
            print("   제%-3d조 %-24s 이익 %d · 반론 %d"
                  % (no, (n.get("title") or "")[:24], len(ben), len(obj)))
        else:
            skip += 1
    if miss:
        raise SystemExit("찾지 못한 조문: %s" % miss)
    print("   —— 붙임 %d · 건너뜀 %d" % (done, skip))
    if WRITE and done:
        json.dump(doc, io.open(SRC, "w", encoding="utf-8", newline="\n"),
                  ensure_ascii=False, indent=1)
        print("적었습니다 — %s" % os.path.relpath(SRC, ROOT))
    elif not WRITE:
        print("보여만 주었습니다 —— 적으려면 --write 를 붙이십시오.")


if __name__ == "__main__":
    main()
