BLOCKS = ("○ 현행 규정:", "○ 현행의 문제:", "○ 관련 근거:", "○ 개정 사유:", "○ 개정 내용:")


def cut(reason, tag):
    """사유에서 한 덩이를 떼어 낸다 —— (앞, 그 덩이, 뒤)"""
    i = reason.find(tag)
    if i < 0:
        return None
    later = [reason.find(t, i + 1) for t in BLOCKS]
    j = min([x for x in later if x > i] or [len(reason)])
    return reason[:i], reason[i:j], reason[j:]


def put(node, tag, lines, keep_tail=False):
    """한 덩이를 새 줄로 갈아 끼운다. keep_tail 이면 본디 있던 줄을 뒤에 남긴다."""
    r = node.get("reason") or ""
    got = cut(r, tag)
    assert got, (node.get("no"), tag)
    head, body, tail = got
    old = [l for l in body.split(NL)[1:] if l.strip()]
    new = [tag, ""] + lines
    if keep_tail:
        new = new + [""] + old
    node["reason"] = head + NL.join(new) + NL + NL + tail.lstrip(NL)


